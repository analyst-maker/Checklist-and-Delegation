-- ==============================================================================
-- 10. DATE HELPER: parse_ddmmyyyy
-- Safely parses 'DD/MM/YYYY' or 'YYYY-MM-DD' text strings to PostgreSQL DATE
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.parse_ddmmyyyy(d_text TEXT) 
RETURNS DATE AS $$
DECLARE
    clean_str TEXT;
BEGIN
    IF d_text IS NULL OR TRIM(d_text) = '' THEN
        RETURN NULL;
    END IF;
    clean_str := TRIM(d_text);
    
    -- Handle DD/MM/YYYY
    IF clean_str ~ '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}' THEN
        RETURN TO_DATE(SUBSTRING(clean_str FROM '^[0-9]{1,2}/[0-9]{1,2}/[0-9]{4}'), 'DD/MM/YYYY');
    END IF;

    -- Handle YYYY-MM-DD
    IF clean_str ~ '^[0-9]{4}-[0-9]{1,2}-[0-9]{1,2}' THEN
        RETURN TO_DATE(SUBSTRING(clean_str FROM '^[0-9]{4}-[0-9]{1,2}-[0-9]{1,2}'), 'YYYY-MM-DD');
    END IF;

    -- Handle DD-MM-YYYY
    IF clean_str ~ '^[0-9]{1,2}-[0-9]{1,2}-[0-9]{4}' THEN
        RETURN TO_DATE(SUBSTRING(clean_str FROM '^[0-9]{1,2}-[0-9]{1,2}-[0-9]{4}'), 'DD-MM-YYYY');
    END IF;

    RETURN NULL;
EXCEPTION WHEN OTHERS THEN
    RETURN NULL;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

-- ==============================================================================
-- 11. HELPER: is_template_due
-- Evaluates task frequency schedules (daily, weekly, monthly, etc.)
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.is_template_due(
    p_freq TEXT,
    p_start_date DATE,
    p_last_date DATE,
    p_target_date DATE
)
RETURNS BOOLEAN AS $$
DECLARE
    f TEXT := LOWER(TRIM(COALESCE(p_freq, 'daily')));
    diff_days INT;
    months_diff INT;
    day_of_month INT;
    last_day_of_month INT;
BEGIN
    -- If target is before start date, not due
    IF p_start_date IS NOT NULL AND p_target_date < p_start_date THEN
        RETURN FALSE;
    END IF;

    -- Never generated before
    IF p_last_date IS NULL THEN
        RETURN TRUE;
    END IF;

    -- Already generated on target date or later
    IF p_last_date >= p_target_date THEN
        RETURN FALSE;
    END IF;

    diff_days := p_target_date - p_last_date;
    day_of_month := EXTRACT(DAY FROM p_target_date)::INT;

    CASE f
        WHEN 'daily' THEN
            RETURN TRUE;

        WHEN 'weekly' THEN
            RETURN diff_days >= 7;

        WHEN 'fortnightly', 'fortnight' THEN
            RETURN diff_days >= 14;

        WHEN 'monthly' THEN
            months_diff := (EXTRACT(YEAR FROM p_target_date) - EXTRACT(YEAR FROM p_last_date)) * 12 +
                           (EXTRACT(MONTH FROM p_target_date) - EXTRACT(MONTH FROM p_last_date));
            RETURN months_diff > 1 OR (months_diff = 1 AND day_of_month >= EXTRACT(DAY FROM p_last_date));

        WHEN 'quarterly', 'quarter' THEN
            months_diff := (EXTRACT(YEAR FROM p_target_date) - EXTRACT(YEAR FROM p_last_date)) * 12 +
                           (EXTRACT(MONTH FROM p_target_date) - EXTRACT(MONTH FROM p_last_date));
            RETURN months_diff > 3 OR (months_diff >= 3 AND day_of_month >= EXTRACT(DAY FROM p_last_date));

        WHEN 'half-yearly', 'halfyearly', 'half yearly', 'semi-annually' THEN
            months_diff := (EXTRACT(YEAR FROM p_target_date) - EXTRACT(YEAR FROM p_last_date)) * 12 +
                           (EXTRACT(MONTH FROM p_target_date) - EXTRACT(MONTH FROM p_last_date));
            RETURN months_diff > 6 OR (months_diff >= 6 AND day_of_month >= EXTRACT(DAY FROM p_last_date));

        WHEN 'yearly' THEN
            months_diff := (EXTRACT(YEAR FROM p_target_date) - EXTRACT(YEAR FROM p_last_date)) * 12 +
                           (EXTRACT(MONTH FROM p_target_date) - EXTRACT(MONTH FROM p_last_date));
            RETURN months_diff > 12 OR (months_diff >= 12 AND day_of_month >= EXTRACT(DAY FROM p_last_date));

        WHEN 'end-of-1st-week' THEN
            RETURN day_of_month >= 7 AND (p_last_date < DATE_TRUNC('month', p_target_date)::DATE + INTERVAL '6 days');

        WHEN 'end-of-2nd-week' THEN
            RETURN day_of_month >= 14 AND (p_last_date < DATE_TRUNC('month', p_target_date)::DATE + INTERVAL '13 days');

        WHEN 'end-of-3rd-week' THEN
            RETURN day_of_month >= 21 AND (p_last_date < DATE_TRUNC('month', p_target_date)::DATE + INTERVAL '20 days');

        WHEN 'end-of-4th-week' THEN
            RETURN day_of_month >= 28 AND (p_last_date < DATE_TRUNC('month', p_target_date)::DATE + INTERVAL '27 days');

        WHEN 'end-of-last-week' THEN
            last_day_of_month := EXTRACT(DAY FROM (DATE_TRUNC('month', p_target_date) + INTERVAL '1 month - 1 day'))::INT;
            RETURN day_of_month >= (last_day_of_month - 2) AND (p_last_date < DATE_TRUNC('month', p_target_date)::DATE + (last_day_of_month - 3) * INTERVAL '1 day');

        WHEN 'one-time', 'critical', 'urgent' THEN
            RETURN FALSE;

        ELSE
            RETURN FALSE;
    END CASE;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

-- ==============================================================================
-- 12. STORED PROCEDURE: generate_checklist_tasks
-- Generates due Checklist tasks from Unique templates for any target date
-- Callable from Supabase RPC, Cron, or SQL Editor:
--   SELECT public.generate_checklist_tasks();
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.generate_checklist_tasks(
    p_target_date DATE DEFAULT (CURRENT_DATE AT TIME ZONE 'Asia/Kolkata')::DATE
)
RETURNS JSONB AS $$
DECLARE
    r RECORD;
    v_today_str TEXT;
    v_now_ts TEXT;
    v_next_task_id BIGINT;
    v_generated_count INT := 0;
    v_template_start_date DATE;
    v_template_last_date DATE;
    v_is_due BOOLEAN;
    v_exists BOOLEAN;
BEGIN
    v_today_str := TO_CHAR(p_target_date, 'DD/MM/YYYY');
    v_now_ts := TO_CHAR(NOW() AT TIME ZONE 'Asia/Kolkata', 'DD/MM/YYYY, HH12:MI:SS AM');

    -- Calculate current highest Task ID in Checklist table
    SELECT COALESCE(MAX("Task ID"), 0) INTO v_next_task_id FROM public."Checklist";

    -- Loop through all active templates in Unique table
    FOR r IN 
        SELECT 
            "Task ID",
            "Department",
            "Give By",
            "Name",
            "Task Description",
            "Task Start date",
            "Frequency",
            "Enable Reminder",
            "Require Attatchment",
            "Last Date"
        FROM public."Unique"
        ORDER BY "Task ID" ASC
    LOOP
        v_template_start_date := public.parse_ddmmyyyy(r."Task Start date");
        v_template_last_date := public.parse_ddmmyyyy(r."Last Date");

        v_is_due := public.is_template_due(
            r."Frequency",
            v_template_start_date,
            v_template_last_date,
            p_target_date
        );

        IF v_is_due THEN
            -- Deduplication check: verify task doesn't already exist for this date
            SELECT EXISTS(
                SELECT 1 FROM public."Checklist"
                WHERE LOWER(TRIM("Name")) = LOWER(TRIM(COALESCE(r."Name", '')))
                  AND LOWER(TRIM(COALESCE("Tast Descriptions", ''))) = LOWER(TRIM(COALESCE(r."Task Description", '')))
                  AND "Task Start Date" = v_today_str
            ) INTO v_exists;

            IF NOT v_exists THEN
                v_next_task_id := v_next_task_id + 1;

                INSERT INTO public."Checklist" (
                    "Task ID",
                    "Timestamp",
                    "Department",
                    "Given By",
                    "Name",
                    "Tast Descriptions",
                    "Task Start Date",
                    "Freq",
                    "Enable Reminders",
                    "Require Attachment",
                    "Actual",
                    "Delay",
                    "Status",
                    "Remarks",
                    "Uploaded Image"
                ) VALUES (
                    v_next_task_id,
                    v_now_ts,
                    r."Department",
                    COALESCE(r."Give By", 'Admin'),
                    r."Name",
                    r."Task Description",
                    v_today_str,
                    COALESCE(r."Frequency", 'daily'),
                    COALESCE(r."Enable Reminder", 'Yes'),
                    COALESCE(r."Require Attatchment", 'No'),
                    NULL,
                    NULL,
                    NULL,
                    NULL,
                    NULL
                );

                v_generated_count := v_generated_count + 1;
            END IF;

            -- Update Last Date in Unique template
            UPDATE public."Unique"
            SET "Last Date" = v_today_str
            WHERE "Task ID" = r."Task ID";
        END IF;
    END LOOP;

    RETURN jsonb_build_object(
        'success', true,
        'target_date', v_today_str,
        'tasks_generated', v_generated_count,
        'message', FORMAT('Successfully generated %s task(s) for %s', v_generated_count, v_today_str)
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Grant execution permission to anon and authenticated roles
GRANT EXECUTE ON FUNCTION public.generate_checklist_tasks(DATE) TO anon, authenticated, service_role;

